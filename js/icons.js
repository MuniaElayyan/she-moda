/* ---------------------------------------------------------------------------
   إرجاع أيقونة جاهزة كنص HTML
   name    : اسم الأيقونة من القائمة أعلاه
   classes : أصناف Tailwind للحجم واللون
   --------------------------------------------------------------------------- */
SheModa.icon = function (name, classes) {
  var path = SheModa.iconPaths[name];
  if (!path) return '';

  return (
    '<svg viewBox="0 0 24 24" class="' +
    (classes || 'w-5 h-5') +
    '" fill="none" stroke="currentColor" stroke-width="1.6" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
    path +
    '</svg>'
  );
};

/* ---------------------------------------------------------------------------
   تنظيف النصوص قبل إدراجها في HTML — حماية بسيطة ضد كسر الصفحة
   --------------------------------------------------------------------------- */
SheModa.esc = function (value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
};
